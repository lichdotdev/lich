const (
	soulsCells = 11
	soulsStep  = 70 * time.Millisecond
)

// soulsSize is the side the status sprites are drawn at in the corner slot:
// smaller than the provider mark's box, so the corner reads as a mark beside
// the name and not as a second icon.
var soulsSize = unit.Dp(16)

// soulsFrame is the frame showing at now, and when the next one starts. A
// time before the epoch (a context that never set Now) still lands on a frame.
func soulsFrame(now time.Time) (frame int, next time.Time) {
	tick := now.UnixNano() / int64(soulsStep)
	n := int64(len(soulsFrames))
	return int((tick%n + n) % n), time.Unix(0, (tick+1)*int64(soulsStep))
}

// soulsSpinner draws the spinner centered in gtx's minimum size and asks for
// the next frame. Only a working session's row draws it.
func soulsSpinner(gtx C, th *ui.Theme) D {
	frame, next := soulsFrame(gtx.Now)
	nextFrame(gtx, th, next.Sub(gtx.Now))
	return drawSprite(gtx, th, soulsFrames[frame])
}
